#!/usr/bin/env bash
# greyGiraffe – start the whole app in Docker on a laptop (Mac/Linux). Needs only Docker Desktop.
#   ./scripts/docker-up.sh            build + start, wait until ready, print the URL
#   ./scripts/docker-up.sh down       stop (data is kept)
#   ./scripts/docker-up.sh reset      wipe data and start fresh
#   ./scripts/docker-up.sh logs       follow the app log
set -euo pipefail
cd "$(dirname "$0")/.."
ENV_FILE=.env.docker
COMPOSE=(docker compose -f docker-compose.prod.yml --env-file "$ENV_FILE")
bold() { printf '\n\033[1m%s\033[0m\n' "$*"; }
die()  { printf '\033[31m%s\033[0m\n' "$*" >&2; exit 1; }

command -v docker >/dev/null || die "Docker is not installed. Get Docker Desktop: https://www.docker.com/products/docker-desktop/"
if ! docker info >/dev/null 2>&1; then
  if [ "$(uname)" = "Darwin" ]; then
    echo "Docker is not running – starting Docker Desktop…"; open -a Docker
    for i in $(seq 1 60); do docker info >/dev/null 2>&1 && break; sleep 2; done
  fi
  docker info >/dev/null 2>&1 || die "Docker is not running. Start Docker Desktop and re-run."
fi

case "${1:-up}" in
  down)  "${COMPOSE[@]}" down; echo "stopped (data kept in Docker volumes)"; exit 0 ;;
  reset) "${COMPOSE[@]}" down -v; echo "data wiped"; ;;
  logs)  exec "${COMPOSE[@]}" logs -f app ;;
  up|"") ;;
  *) die "usage: $0 [up|down|reset|logs]" ;;
esac

bold "1/3 Settings"
if [ ! -f "$ENV_FILE" ]; then
  rand() { openssl rand -hex 24 2>/dev/null || date +%s%N; }
  cat > "$ENV_FILE" <<ENV
# generated by scripts/docker-up.sh for a laptop – edit AUTH_URL if you open the app from another device
APP_PORT=8080
AUTH_URL=http://localhost:8080
AUTH_SECRET=$(rand)
CRON_SECRET=$(rand)
POSTGRES_PASSWORD=$(rand)
DEMO_DATE=2026-10-09
ADMIN_USERNAMES=alice
SEED_DEMO=true
IMPORT_ON_START=true
IMPORT_TIMES=05:00,09:30
ENV
  echo "created $ENV_FILE (port 8080, demo mode, random secrets)"
else
  echo "using existing $ENV_FILE"
fi
APP_PORT=$(grep -E '^APP_PORT=' "$ENV_FILE" | cut -d= -f2); APP_PORT=${APP_PORT:-8080}
AUTH_URL=$(grep -E '^AUTH_URL=' "$ENV_FILE" | cut -d= -f2)

bold "2/3 Build + start (first time: a few minutes)"
"${COMPOSE[@]}" up -d --build

bold "3/3 Waiting for the app (first boot imports menus + demo data, ~1 min)"
for i in $(seq 1 120); do
  if curl -fsS "http://127.0.0.1:${APP_PORT}/api/health" >/dev/null 2>&1; then
    echo; echo "  Ready:  ${AUTH_URL}"; echo "  Login:  alice / password123   (also bob, carol)"
    echo; echo "  Logs:   ./scripts/docker-up.sh logs      Stop: ./scripts/docker-up.sh down      Fresh start: ./scripts/docker-up.sh reset"
    exit 0
  fi
  if ! "${COMPOSE[@]}" ps --status running --services 2>/dev/null | grep -q '^app$'; then
    echo "app container is not running – last log lines:"; "${COMPOSE[@]}" logs --tail 30 app; exit 1
  fi
  sleep 5
done
echo "still not ready after 10 minutes – check: ./scripts/docker-up.sh logs"; exit 1
